export const TENANTS_BY_ID = Object.fromEntries(TENANTS.map((t) => [t.id, t]));

export function getTenant(id) {
  return TENANTS_BY_ID[id] || null;
}

export function findTenantByFirstName(text) {
  if (!text) return null;
  const lowered = text.toLowerCase();
  return TENANTS.find((t) => lowered.includes(t.firstName.toLowerCase())) || null;
}
